// ── Language helpers ──
let currentLang = localStorage.getItem('fw_lang') || 'ja';

function t(key, vars = {}) {
  const str = TRANSLATIONS[currentLang]?.[key] || TRANSLATIONS['ja']?.[key] || key;
  return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] !== undefined ? vars[k] : `{${k}}`);
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('fw_lang', lang);
  document.documentElement.lang = lang;
  // Re-render the page by dispatching a custom event
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  updateLangBtn();
}

function toggleLang() {
  setLang(currentLang === 'ja' ? 'en' : 'ja');
}

function updateLangBtn() {
  const btn = document.getElementById('langBtn');
  if (btn) btn.textContent = t('lang_switch');
}
